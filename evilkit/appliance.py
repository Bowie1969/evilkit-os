"""EvilKit OS — bake the operator system into a bootable appliance image.

Pure, stdlib-only seed generation. Given an :class:`ApplianceSpec`, it renders
the artifacts a cloud-init NoCloud datasource (or a first-boot hook on a raw
image) consumes: the ``user-data`` / ``meta-data`` seed, a first-boot
``bootstrap.sh``, and the systemd unit that runs it. Nothing here touches the
network or builds an image — it only produces text, so it is safe to run and
trivially testable.

The appliance runs the *consolidated operator system* (the scope-gated launcher,
the harness, the evidence journal and the mesh worker) as a single bootable
node: first boot provisions the box, installs the package, records the scope,
writes a manifest, and (optionally) registers with a mesh leader.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

__all__ = [
    "ApplianceSpec",
    "SERVICE_NAME",
    "BOOTSTRAP_PATH",
    "render_user_data",
    "render_bootstrap",
    "render_systemd_unit",
    "render_meta_data",
    "render_manifest",
    "write_seed",
]

DEFAULT_INSTALL_SOURCE = "git+https://github.com/Bowie1969/evilkit"
SERVICE_NAME = "evilkit-os.service"
BOOTSTRAP_PATH = "/opt/evilkit-os/bootstrap.sh"
CONFIG_PATH = "/etc/evilkit-os/config.toml"
TOKEN_PATH = "/etc/evilkit-os/mesh-token"
DROP_DIR = "/opt/drop"
MANIFEST_PATH = "/opt/evilkit-os/manifest.json"

_DEFAULT_PACKAGES = ("openssh-server", "git", "python3-venv")


@dataclass
class ApplianceSpec:
    hostname: str = "evilkit-os"
    admin_user: str = "operator"
    ssh_keys: list[str] = field(default_factory=list)
    scope: str = "solo"
    mesh_leader: str | None = None
    mesh_token: str | None = None
    install_source: str = DEFAULT_INSTALL_SOURCE
    packages: list[str] = field(default_factory=lambda: list(_DEFAULT_PACKAGES))
    timezone: str = "UTC"

    def validate(self) -> list[str]:
        """Return a list of human-readable problems; empty means valid."""
        problems: list[str] = []
        if not self.hostname or any(ch.isspace() for ch in self.hostname):
            problems.append("hostname must be a single non-empty token")
        if not self.admin_user or any(ch.isspace() for ch in self.admin_user):
            problems.append("admin_user must be a single non-empty token")
        if self.mesh_leader is not None and not self.mesh_leader.startswith(("http://", "https://")):
            problems.append("mesh_leader must be an http(s) URL")
        if (self.mesh_leader is None) != (self.mesh_token is None):
            problems.append("mesh_leader and mesh_token must be given together")
        return problems


def render_bootstrap(spec: ApplianceSpec) -> str:
    """First-boot bootstrap script: idempotent, logs to a file and the journal."""
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by `evilkit appliance seed` -- do not edit by hand.",
        "set -euo pipefail",
        'log="/var/log/evilkit-os-bootstrap.log"',
        'exec >> "$log" 2>&1',
        f'echo "[bootstrap] starting for {spec.hostname}"',
        f'mkdir -p /opt/evilkit-os "{DROP_DIR}" /etc/evilkit-os',
        f'chmod 0777 "{DROP_DIR}"',
    ]
    if spec.mesh_token is not None:
        lines += [
            # Token is already placed 0600 by cloud-init; nothing to write here.
            f'echo "[bootstrap] mesh token present at {TOKEN_PATH}"',
        ]
    lines += [
        f'if ! command -v evilkit >/dev/null 2>&1; then',
        f'  echo "[bootstrap] installing {spec.install_source}"',
        '  python3 -m venv /opt/evilkit-os/venv',
        '  /opt/evilkit-os/venv/bin/pip install --upgrade pip wheel',
        f'  /opt/evilkit-os/venv/bin/pip install "{spec.install_source}"',
        '  ln -sf /opt/evilkit-os/venv/bin/evilkit /usr/local/bin/evilkit',
        'else',
        '  echo "[bootstrap] evilkit already present, skipping install"',
        'fi',
        f'cat > "{CONFIG_PATH}" <<EOF',
        '# EvilKit OS appliance config (generated at first boot)',
        f'hostname = "{spec.hostname}"',
        f'scope = "{spec.scope}"',
    ]
    if spec.mesh_leader is not None:
        lines += [f'mesh_leader = "{spec.mesh_leader}"']
    lines += [
        'EOF',
        f'echo "[bootstrap] scope={spec.scope} hostname={spec.hostname}"',
    ]
    if spec.mesh_leader is not None:
        lines += [
            f'echo "[bootstrap] mesh leader {spec.mesh_leader}; '
            f'register out of band (token at {TOKEN_PATH})"',
        ]
    # Sentinel manifest: the unit is ConditionPathExists=!manifest, so this also
    # guarantees the bootstrap runs at most once.
    lines += [
        f'cat > "{MANIFEST_PATH}" <<EOF',
        f'{{"hostname": "{spec.hostname}", "bootstrapped_at": "$(date -Is)"}}',
        'EOF',
        'echo "[bootstrap] done"',
    ]
    return "\n".join(lines) + "\n"


def render_systemd_unit(spec: ApplianceSpec) -> str:
    return (
        "[Unit]\n"
        f"Description=EvilKit OS first-boot bootstrap for {spec.hostname}\n"
        "After=network-online.target\n"
        "Wants=network-online.target\n"
        f"ConditionPathExists=!{MANIFEST_PATH}\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        f"ExecStart={BOOTSTRAP_PATH}\n"
        "RemainAfterExit=yes\n"
        "StandardOutput=journal\n"
        "\n"
        "[Install]\n"
        "WantedBy=multi-user.target\n"
    )


def render_meta_data(spec: ApplianceSpec) -> str:
    return f"instance-id: {spec.hostname}\nlocal-hostname: {spec.hostname}\n"


def render_user_data(spec: ApplianceSpec) -> str:
    """cloud-init ``#cloud-config`` that provisions the box and runs the bootstrap."""
    write_files = [
        {
            "path": BOOTSTRAP_PATH,
            "permissions": "0755",
            "content": render_bootstrap(spec),
        },
        {
            "path": f"/etc/systemd/system/{SERVICE_NAME}",
            "permissions": "0644",
            "content": render_systemd_unit(spec),
        },
    ]
    if spec.mesh_token is not None:
        # The token is a secret: it lands 0600 root:root and never in a manifest.
        write_files.append(
            {
                "path": TOKEN_PATH,
                "permissions": "0600",
                "owner": "root:root",
                "content": spec.mesh_token,
            }
        )

    body = {
        "hostname": spec.hostname,
        "manage_etc_hosts": True,
        "timezone": spec.timezone,
        "package_update": False,
        "package_upgrade": False,
        "packages": list(spec.packages),
        "users": [
            {
                "name": spec.admin_user,
                "sudo": "ALL=(ALL) NOPASSWD:ALL",
                "shell": "/bin/bash",
                "lock_passwd": True,
                "ssh_authorized_keys": list(spec.ssh_keys),
            }
        ],
        "ssh_pwauth": False,
        "disable_root": True,
        "write_files": write_files,
        "runcmd": [
            f"systemctl enable {SERVICE_NAME}",
            f"systemctl start {SERVICE_NAME}",
        ],
    }

    return "#cloud-config\n" + _dump_mapping(body, 0) + "\n"


def _scalar(value) -> str:
    """Render one scalar as a YAML double-quoted string, bool or int.

    Double-quoting scalars keeps multi-line strings (the bootstrap script, the
    systemd unit) unambiguous: YAML's double-quote escapes turn ``\\n`` back into
    a real newline, which is exactly what cloud-init expects for write_files.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value))


def _dump_mapping(obj: dict, indent: int, dash: str = "") -> str:
    """Render a mapping. ``dash`` is ``"- "`` when the mapping is a list item."""
    pad = " " * indent
    cont = " " * len(dash)  # aligns subsequent keys under the first key after "- "
    out: list[str] = []
    first = True
    for key, value in obj.items():
        if value is None:
            continue
        prefix = pad + (dash if first else cont)
        if isinstance(value, dict):
            out.append(f"{prefix}{key}:")
            out.append(_dump_mapping(value, indent + len(dash) + 2))
        elif isinstance(value, list):
            out.append(f"{prefix}{key}:")
            out.append(_dump_sequence(value, indent + len(dash) + 2))
        else:
            out.append(f"{prefix}{key}: {_scalar(value)}")
        first = False
    return "\n".join(out)


def _dump_sequence(obj: list, indent: int) -> str:
    pad = " " * indent
    out: list[str] = []
    for item in obj:
        if isinstance(item, dict):
            out.append(_dump_mapping(item, indent, dash="- "))
        elif isinstance(item, list):
            out.append(f"{pad}- ")
            out.append(_dump_sequence(item, indent + 2))
        else:
            out.append(f"{pad}- {_scalar(item)}")
    return "\n".join(out)


def render_manifest(spec: ApplianceSpec) -> dict:
    """A build-time manifest. Never carries the mesh token or private keys."""
    return {
        "generator": "evilkit appliance",
        "hostname": spec.hostname,
        "admin_user": spec.admin_user,
        "scope": spec.scope,
        "mesh_leader": spec.mesh_leader,
        "mesh_token": "present" if spec.mesh_token else None,
        "install_source": spec.install_source,
        "timezone": spec.timezone,
        "ssh_key_count": len(spec.ssh_keys),
    }


def write_seed(spec: ApplianceSpec, out_dir: Path) -> dict[str, Path]:
    """Render every artifact into ``out_dir`` and return the files written."""
    problems = spec.validate()
    if problems:
        raise ValueError("; ".join(problems))

    out_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "user-data": render_user_data(spec),
        "meta-data": render_meta_data(spec),
        "bootstrap.sh": render_bootstrap(spec),
        "evilkit-os.service": render_systemd_unit(spec),
        "manifest.json": json.dumps(render_manifest(spec), indent=2) + "\n",
    }
    written: dict[str, Path] = {}
    for name, content in files.items():
        path = out_dir / name
        path.write_text(content, encoding="utf-8")
        written[name] = path
    return written
